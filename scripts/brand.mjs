#!/usr/bin/env bun
/**
 * Regenerates everything drawn from the logo in packages/shared/src/brand.ts:
 *
 *   bun run brand
 *
 * 1. The wordmark outline (packages/shared/src/brand-wordmark.ts), from the font.
 * 2. App icons, adaptive icon layers, splash and favicon (apps/mobile/assets).
 * 3. The landing page's logo, favicon and touch icon (landing/).
 * 4. The PNG logo emails use (apps/api/src/brand/email-logo.ts).
 *
 * Run with Bun: it imports the TypeScript source directly.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const at = (p) => join(root, p);

// 1. Wordmark: "buddy" in Schibsted Grotesk ExtraBold, tracked -0.045em, as in the design.
// Sized against the 48-unit mark (52px type beside a 48px mark), centred the way
// CSS centres a line of text next to it.
const WORDMARK_FONT =
  'node_modules/@expo-google-fonts/schibsted-grotesk/800ExtraBold/SchibstedGrotesk_800ExtraBold.ttf';
const WORDMARK_TEXT = 'buddy';
const SIZE = 52;
const TRACKING = -0.045;
const MARK_CENTRE = 24;

const font = opentype.loadSync(at(WORDMARK_FONT));
const scale = SIZE / font.unitsPerEm;
const baseline = MARK_CENTRE + ((font.ascender + font.descender) / 2) * scale;
const glyphs = font.getPath(WORDMARK_TEXT, 0, baseline, SIZE, { letterSpacing: TRACKING });
const bounds = glyphs.getBoundingBox();
const shifted = font.getPath(WORDMARK_TEXT, -bounds.x1, baseline, SIZE, {
  letterSpacing: TRACKING,
});
const r = (n) => Math.round(n * 100) / 100;
writeFileSync(
  at('packages/shared/src/brand-wordmark.ts'),
  `// Generated by \`bun run brand\` from ${WORDMARK_FONT.split('/').pop()}. Don't edit by hand.\n` +
    `export const WORDMARK = {\n` +
    `  width: ${r(bounds.x2 - bounds.x1)},\n` +
    `  top: ${r(bounds.y1)},\n` +
    `  bottom: ${r(bounds.y2)},\n` +
    `  d: '${shifted.toPathData(2)}',\n` +
    `};\n`,
);

// Imported after writing the wordmark, so this run uses the new one.
const {
  logoSvg,
  logoTileSvg: markOn,
  LOGO_TONES,
} = await import('../packages/shared/src/brand.ts');
const BG = LOGO_TONES.dark.background;

// Each SVG states its pixel size, so the default 72dpi renders it at exactly that size.
const png = (svg, path, { flatten } = {}) => {
  let img = sharp(Buffer.from(svg));
  if (flatten) img = img.flatten({ background: flatten });
  return img.png({ compressionLevel: 9 }).toFile(at(path));
};

// 2. App. The app icon tile matches the design's 96px tile (62px-wide mark);
// Android's adaptive foreground keeps the mark inside the 66% safe zone.
const assets = 'apps/mobile/assets';
await png(markOn(1024, { fraction: 0.646, background: BG }), `${assets}/icon.png`, {
  flatten: BG, // iOS rejects icons with transparency.
});
await png(markOn(1024, { fraction: 0.5 }), `${assets}/android-icon-foreground.png`);
await png(
  `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="${BG}"/></svg>`,
  `${assets}/android-icon-background.png`,
);
await png(markOn(1024, { fraction: 0.5, tone: 'mono' }), `${assets}/android-icon-monochrome.png`);
// Shown at 120pt wide by expo-splash-screen (app.json); drawn at 4x.
await png(markOn(480, { fraction: 1 }), `${assets}/splash-icon.png`);
await png(markOn(48, { fraction: 0.74, background: BG, radius: 11 }), `${assets}/favicon.png`);

// 3. Landing page: favicons, and the inline <symbol> the page reuses.
writeFileSync(
  at('landing/favicon.svg'),
  markOn(64, { fraction: 0.74, background: BG, radius: 14 }),
);
await png(markOn(180, { fraction: 0.646, background: BG }), 'landing/apple-touch-icon.png', {
  flatten: BG,
});
const landing = at('landing/index.html');
const symbol = logoSvg({ variant: 'mark', title: '', id: 'logo-cut' })
  .replace(/^<svg[^>]*>/, '<symbol id="logo" viewBox="0 0 74 48">')
  .replace(/<\/svg>$/, '</symbol>');
const html = readFileSync(landing, 'utf8');
const marked = /(<!-- brand:logo -->)[\s\S]*?(<!-- \/brand:logo -->)/;
if (!marked.test(html)) throw new Error('landing/index.html is missing the brand:logo markers');
writeFileSync(landing, html.replace(marked, `$1\n      ${symbol}\n      $2`));

// 4. Email: most mail apps don't show SVG, so a PNG served by the API.
const email = await sharp(Buffer.from(logoSvg({ tone: 'light', height: 64 })), { density: 300 })
  .resize({ height: 64 })
  .png({ compressionLevel: 9 })
  .toBuffer();
mkdirSync(at('apps/api/src/brand'), { recursive: true });
writeFileSync(
  at('apps/api/src/brand/email-logo.ts'),
  `// Generated by \`bun run brand\`: the full logo on white, 64px tall, as a PNG.\n` +
    `export const EMAIL_LOGO = { width: ${(await sharp(email).metadata()).width}, height: 64, base64: '${email.toString('base64')}' };\n`,
);

// Keep the generated text files in the repo's formatting.
spawnSync(
  'bunx',
  [
    'prettier',
    '--write',
    'packages/shared/src/brand-wordmark.ts',
    'apps/api/src/brand/email-logo.ts',
    'landing/index.html',
  ],
  { cwd: root, stdio: 'ignore' },
);
console.log('Logo assets regenerated.');
