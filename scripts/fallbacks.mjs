#!/usr/bin/env node
/**
 * Pulls the fallback artwork out of the Claude Design file
 * (design/fallbacks/Buddy_Fallbacks.dc.html) into apps/api/src/brand/fallback-art.ts,
 * which the API serves at /fallbacks/<id>.svg:
 *
 *   bun run fallbacks
 *
 * Run it again after changing the design. Which picture goes where is
 * decided in apps/api/src/lib/fallbacks.ts, not here.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'design/fallbacks/Buddy_Fallbacks.dc.html');
const target = join(root, 'apps/api/src/brand/fallback-art.ts');

const html = readFileSync(source, 'utf8');
const art = {};
for (const match of html.matchAll(/<svg id="fb-([a-z0-9-]+)"([^>]*)>([\s\S]*?)<\/svg>/g)) {
  const [, id, attrs, body] = match;
  const viewBox = /viewBox="([^"]+)"/.exec(attrs)[1];
  const [, , width, height] = viewBox.split(' ').map(Number);
  // Standalone files: drawn at the design's own size, cropped like the page did.
  const aspect = /preserveAspectRatio="([^"]+)"/.exec(attrs)?.[1];
  art[id] =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${width}" height="${height}"` +
    `${aspect ? ` preserveAspectRatio="${aspect}"` : ''}>${body.trim()}</svg>`;
}
if (Object.keys(art).length === 0) throw new Error(`No artwork found in ${source}`);

writeFileSync(
  target,
  `// Generated by scripts/fallbacks.mjs from design/fallbacks/Buddy_Fallbacks.dc.html. Don't edit.\n` +
    `export const FALLBACK_ART: Record<string, string> = ${JSON.stringify(art, null, 2)};\n`,
);
console.log(`${Object.keys(art).length} pictures → ${target}`);
