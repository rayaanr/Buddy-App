/**
 * Prints the SQL that loads Sri Lanka's towns into `places`, for a migration.
 *
 *   npx tsx scripts/places/build.ts > drizzle/00xx_places_data.sql
 *
 * Sources (both MIT): postal towns with coordinates and Sinhala/Tamil names
 * from `sri-lanka-postal-locations` (derived from
 * madurapa/sri-lanka-provinces-districts-cities), and which towns have a main
 * post office from `lankapost`. Ids are the first dataset's own, so a
 * regenerated list updates rows in place.
 */
import { getAll as getPostOffices } from 'lankapost';
import { getAllCities, getDistrictById, getProvinceById } from 'sri-lanka-postal-locations';

/** Post-office-only entries that aren't places people live or meet. */
const NOT_PLACES = new Set([
  'Colombo General Hospital',
  'Colombo Kachcheri',
  'Colombo Labour Sec',
  'Colombo Secretariant',
  'National Museum of Colombo',
  'Katunayake Air Force Camp',
  'Panagoda Army Camp',
  'Parliament of Sri Lanka',
  'University of Colombo',
  'Vidyodaya University',
]);

const mainPostOffice = new Set(
  getPostOffices()
    .filter((p) => p.post_office_type.trim() === 'Main Post Office')
    .map((p) => p.place_name.trim().toLowerCase()),
);

const text = (s: string | null | undefined) => (s ? `'${s.replace(/'/g, "''").trim()}'` : 'null');

const cities = getAllCities();
const at = (c: { latitude: string; longitude: string }) => `${c.latitude},${c.longitude}`;
// Colombo's numbered areas carry their other name ("Colombo 7" is Cinnamon
// Gardens); drop the separate entries for those names at the same spot.
const colomboAliases = new Set(
  cities
    .filter((c) => /^Colombo \d+$/.test(c.name_en) && c.sub_name_en)
    .map((c) => `${c.sub_name_en!.toLowerCase()}@${at(c)}`),
);

const rows: string[] = [];
for (const c of cities) {
  if (NOT_PLACES.has(c.name_en)) continue;
  if (colomboAliases.has(`${c.name_en.toLowerCase()}@${at(c)}`)) continue;
  const district = getDistrictById(c.district_id);
  const province = district && getProvinceById(district.province_id);
  if (!district || !province) continue;
  const colombo = /^Colombo \d+$/.test(c.name_en);
  // "Colombo 7" is also known as "Cinnamon Gardens"; elsewhere the sub-name is a translation.
  const aka = colombo ? c.sub_name_en : null;
  const main = colombo || mainPostOffice.has(c.name_en.toLowerCase());
  rows.push(
    `(${Number(c.id)}, ${text(c.name_en)}, ${text(aka)}, ${text(c.name_si)}, ${text(c.name_ta)}, ` +
      `${text(district.name_en)}, ${text(province.name_en)}, ` +
      `ST_SetSRID(ST_MakePoint(${Number(c.longitude)}, ${Number(c.latitude)}), 4326)::geography, ${main})`,
  );
}

process.stdout.write(
  `-- ${rows.length} towns. Generated by scripts/places/build.ts; don't edit by hand.\n` +
    `INSERT INTO "places" ("id", "name", "aka", "name_si", "name_ta", "district", "province", "location", "main") VALUES\n` +
    rows.join(',\n') +
    `\nON CONFLICT ("id") DO UPDATE SET "name" = excluded."name", "aka" = excluded."aka", ` +
    `"name_si" = excluded."name_si", "name_ta" = excluded."name_ta", "district" = excluded."district", ` +
    `"province" = excluded."province", "location" = excluded."location", "main" = excluded."main";\n` +
    `--> statement-breakpoint\n` +
    // Three or more places at one point means a placeholder (the source's
    // fallback for small villages), except for the district's own town.
    `UPDATE "places" p SET "approximate" = (p."name" <> p."district" AND (` +
    `SELECT count(*) FROM "places" q WHERE ST_Equals(q."location"::geometry, p."location"::geometry)) >= 3);\n`,
);
